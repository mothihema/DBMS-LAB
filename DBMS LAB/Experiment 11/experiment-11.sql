SELECT AUTHOR.Author_ID, AUTHOR.Author_Name, SUBJECT.Subject_Name
FROM AUTHOR
JOIN SUBJECT ON AUTHOR.Subject_ID = SUBJECT.Subject_ID;

SELECT PUBLICATION.Publication_ID, PUBLICATION.Publication_Name,
       AUTHOR.Author_Name, EDITOR.Editor_Name, SUBJECT.Subject_Name
FROM PUBLICATION
JOIN AUTHOR ON PUBLICATION.Author_ID = AUTHOR.Author_ID
JOIN EDITOR ON PUBLICATION.Editor_ID = EDITOR.Editor_ID
JOIN SUBJECT ON PUBLICATION.Subject_ID = SUBJECT.Subject_ID;

SELECT SUBJECT.Subject_Name, COUNT(PUBLICATION.Publication_ID) AS Publication_Count
FROM SUBJECT
LEFT JOIN PUBLICATION ON SUBJECT.Subject_ID = PUBLICATION.Subject_ID
GROUP BY SUBJECT.Subject_Name;

SELECT EDITOR.Editor_Name, COUNT(PUBLICATION.Publication_ID) AS Publication_Count
FROM EDITOR
LEFT JOIN PUBLICATION ON EDITOR.Editor_ID = PUBLICATION.Editor_ID
GROUP BY EDITOR.Editor_Name;